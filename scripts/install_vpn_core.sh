systemctl daemon-reload
systemctl enable openvpn-server@server xray ocserv strongswan-starter xl2tpd wg-quick@wg0 >/dev/null 2>&1 || true
systemctl restart openvpn-server@server || CORE_ERRORS+=(openvpn-restart)
ensure_xray_runtime_permissions
systemctl restart xray || CORE_ERRORS+=(xray-restart)
systemctl restart ocserv || CORE_ERRORS+=(ocserv-restart)
systemctl restart strongswan-starter || systemctl restart strongswan || ipsec restart || CORE_ERRORS+=(ipsec-restart)
systemctl restart xl2tpd || CORE_ERRORS+=(xl2tpd-restart)
systemctl restart wg-quick@wg0 || CORE_ERRORS+=(wireguard-restart)
# v18 legacy/new cores
if [[ -x "$APP_DIR/scripts/repair_pptp.sh" ]]; then bash "$APP_DIR/scripts/repair_pptp.sh" || CORE_ERRORS+=(pptp-repair); fi
if [[ -x "$APP_DIR/scripts/repair_hysteria2.sh" ]]; then HYSTERIA2_PORT=${HYSTERIA2_PORT:-4433}
SSH_PORT=${SSH_PORT:-422} HYSTERIA2_UP="${HYSTERIA2_UP:-100 mbps}" HYSTERIA2_DOWN="${HYSTERIA2_DOWN:-300 mbps}" bash "$APP_DIR/scripts/repair_hysteria2.sh" || CORE_ERRORS+=(hysteria2-repair); fi
if command -v ocserv >/dev/null 2>&1; then
  systemctl is-active --quiet ocserv || CORE_ERRORS+=(ocserv-inactive)
  ss -lnt 2>/dev/null | awk '{print $4}' | grep -Eq "(^|:)${OCSERV_TCP}$" || CORE_ERRORS+=(ocserv-port-not-listening)
else
  CORE_ERRORS+=(ocserv-binary-missing)
