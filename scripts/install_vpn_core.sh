#!/usr/bin/env bash
set -euo pipefail
CORE_ERRORS=()
APP_DIR=${APP_DIR:-/opt/ironpanel}
WIREGUARD_MTU=${IRONPANEL_WIREGUARD_MTU:-${WIREGUARD_MTU:-1280}}
ETC_DIR=${ETC_DIR:-/etc/ironpanel}
PUBLIC_HOST=${PUBLIC_HOST:-${IRONPANEL_PUBLIC_HOST:-$(hostname -I | awk '{print $1}')}}
OPENVPN_UDP=${OPENVPN_UDP:-1194}
OPENVPN_TCP=${OPENVPN_TCP:-1195}
OPENVPN_PROTO=${OPENVPN_PROTO:-${OPENVPN_TRANSPORT:-udp}}
OPENVPN_PROTO=$(echo "$OPENVPN_PROTO" | tr A-Z a-z)
if [[ "$OPENVPN_PROTO" != "tcp" ]]; then OPENVPN_PROTO=udp; fi
OPENVPN_PORT=$OPENVPN_UDP
if [[ "$OPENVPN_PROTO" == "tcp" ]]; then OPENVPN_PORT=$OPENVPN_TCP; fi
OCSERV_PORT=${OCSERV_PORT:-8445}
OCSERV_TCP=${OCSERV_TCP:-$OCSERV_PORT}
OCSERV_UDP=${OCSERV_UDP:-$OCSERV_PORT}
OCSERV_TRANSPORT=${OCSERV_TRANSPORT:-tcp_udp}
WIREGUARD_PORT=${WIREGUARD_PORT:-51820}
XRAY_PORT=${XRAY_PORT:-443}
XRAY_API_PORT=${XRAY_API_PORT:-10085}
L2TP_PORT=${L2TP_PORT:-1701}
PPTP_PORT=${PPTP_PORT:-1723}
HYSTERIA2_PORT=${HYSTERIA2_PORT:-4433}
SSH_PORT=${SSH_PORT:-422}

# v19.10.10: when this script is executed by Health Repair or manually it may
# not receive the port exports generated by upgrade.sh. Read the persisted
# settings directly from /etc/ironpanel/ironpanel.db so custom ports such as
# Ocserv/OpenConnect tcp/1195 are never reset to defaults.
read_db_runtime_settings(){
  local database_url_value="${DATABASE_URL:-}"
  local db_file="${IRONPANEL_DB:-${database_url_value#sqlite:///}}"
  [[ -n "$db_file" && "$db_file" != "$database_url_value" ]] || db_file="$ETC_DIR/ironpanel.db"
  [[ -s "$db_file" ]] || return 0
  command -v python3 >/dev/null 2>&1 || return 0
  python3 - "$db_file" <<'PYDB'
import re, shlex, sqlite3, sys
db=sys.argv[1]
def val(k, default=''):
    try:
        con=sqlite3.connect(db); cur=con.cursor(); cur.execute('select value from app_setting where key=? limit 1',(k,)); row=cur.fetchone(); con.close()
        return str(row[0]) if row and row[0] not in (None,'') else default
    except Exception:
        return default
def port(k, default):
    x=val(k, str(default)).strip()
    return x if re.fullmatch(r'\d{1,5}', x) and 0<int(x)<=65535 else str(default)
def choice(k, default, allowed):
    x=val(k, default).strip().lower()
    return x if x in allowed else default
vals={
 'OPENVPN_UDP': port('port_openvpn_udp',1194),
 'OPENVPN_TCP': port('port_openvpn_tcp',1195),
 'OPENVPN_PROTO': choice('openvpn_transport','udp',{'udp','tcp'}),
 'OCSERV_PORT': port('port_ocserv_tcp',8445),
 'OCSERV_TCP': port('port_ocserv_tcp',8445),
 'OCSERV_UDP': port('port_ocserv_udp',8445),
 'OCSERV_TRANSPORT': choice('ocserv_transport','tcp_udp',{'tcp','udp','tcp_udp'}),
 'WIREGUARD_PORT': port('port_wireguard_udp',51820),
 'XRAY_PORT': port('port_xray_tcp',443),
 'XRAY_API_PORT': port('port_xray_api',10085),
 'L2TP_PORT': port('port_l2tp_udp',1701),
 'PPTP_PORT': port('port_pptp_tcp',1723),
 'HYSTERIA2_PORT': port('port_hysteria2_udp',4433),
 'SSH_PORT': port('port_ssh_tcp',422),
 'WIREGUARD_MTU': val('wireguard_mtu','1280'),
 'IRONPANEL_WIREGUARD_MTU': val('wireguard_mtu','1280'),
}
print(' '.join(f'{k}={shlex.quote(v)}' for k,v in vals.items()))
PYDB
}
DB_RUNTIME_EXPORTS="$(read_db_runtime_settings || true)"
if [[ -n "$DB_RUNTIME_EXPORTS" ]]; then
  # shellcheck disable=SC2086
  eval "export $DB_RUNTIME_EXPORTS"
  OPENVPN_PORT=$OPENVPN_UDP
  [[ "$OPENVPN_PROTO" == "tcp" ]] && OPENVPN_PORT=$OPENVPN_TCP
fi

# A single TCP address:port cannot be shared by OpenVPN TCP and Ocserv.
# When OpenVPN TCP is selected it gets priority, otherwise generated .ovpn
# profiles can point to a port where OpenVPN is not the listening daemon.
if [[ "$OPENVPN_PROTO" == "tcp" && "$OPENVPN_TCP" == "$OCSERV_TCP" ]]; then
  if [[ "$OPENVPN_TCP" == "8445" ]]; then OCSERV_TCP=8446; else OCSERV_TCP=8445; fi
  OCSERV_PORT="$OCSERV_TCP"
  if [[ -s "$ETC_DIR/ironpanel.db" ]] && command -v python3 >/dev/null 2>&1; then
    python3 - "$ETC_DIR/ironpanel.db" "$OCSERV_TCP" <<'PYFIX' || true
import sqlite3, sys
db, port = sys.argv[1], sys.argv[2]
con=sqlite3.connect(db); cur=con.cursor()
cur.execute("CREATE TABLE IF NOT EXISTS app_setting (id INTEGER PRIMARY KEY AUTOINCREMENT, key VARCHAR(120) UNIQUE, value TEXT)")
for k,v in [('port_ocserv_tcp', port), ('port_conflict_last_fix', f'OpenVPN TCP and Ocserv TCP shared one port; Ocserv TCP moved to {port}.')]:
    cur.execute("INSERT INTO app_setting(key,value) VALUES(?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value", (k,v))
con.commit(); con.close()
PYFIX
  fi
fi

WAN_IF=${WAN_IF:-$(ip route get 1.1.1.1 2>/dev/null | awk '{print $5; exit}')}
mkdir -p "$ETC_DIR" /etc/openvpn/server /etc/wireguard /etc/ocserv /etc/ppp /var/log/openvpn /usr/local/etc/xray /var/log/xray
export DEBIAN_FRONTEND=noninteractive
PREREQ_SCRIPT="$APP_DIR/scripts/install_protocol_prerequisites.sh"
if [[ ! -x "$PREREQ_SCRIPT" ]]; then
  echo "IronPanel prerequisite installer is missing: $PREREQ_SCRIPT" >&2
  exit 20
fi
if ! APP_DIR="$APP_DIR" ETC_DIR="$ETC_DIR" bash "$PREREQ_SCRIPT" --install-all; then
  CORE_ERRORS+=(protocol-prerequisites)
fi
sysctl -w net.ipv4.ip_forward=1 >/dev/null || true
sysctl -w net.ipv6.conf.all.forwarding=1 >/dev/null || true
cat > /etc/sysctl.d/99-ironpanel.conf <<SYSCTL
net.ipv4.ip_forward=1
net.ipv6.conf.all.forwarding=1
SYSCTL
# NAT for every VPN subnet. Duplicate rules are avoided.
ensure_nat(){
  local subnet="$1"
  if [[ -n "${WAN_IF:-}" ]] && ! iptables -t nat -C POSTROUTING -s "$subnet" -o "$WAN_IF" -j MASQUERADE 2>/dev/null; then
    iptables -t nat -A POSTROUTING -s "$subnet" -o "$WAN_IF" -j MASQUERADE || true
  fi
}
ensure_forward(){
  local iface="$1"
  if ! iptables -C FORWARD -i "$iface" -j ACCEPT 2>/dev/null; then iptables -A FORWARD -i "$iface" -j ACCEPT || true; fi
  if ! iptables -C FORWARD -o "$iface" -j ACCEPT 2>/dev/null; then iptables -A FORWARD -o "$iface" -j ACCEPT || true; fi
}
ensure_nat 10.8.0.0/24
ensure_nat 10.44.0.0/24
ensure_nat 10.20.20.0/24
ensure_nat 10.66.66.0/24
ensure_nat 10.70.70.0/24
ensure_forward tun0
ensure_forward vpns0
ensure_forward vpns+
ensure_forward wg0
# Accept VPN listening ports on local firewall. Provider/cloud firewall must also allow them.
for rule in "${OPENVPN_UDP}/udp" "${OPENVPN_TCP}/tcp" "${OCSERV_TCP}/tcp" "${OCSERV_UDP}/udp" "${WIREGUARD_PORT}/udp" "${XRAY_PORT}/tcp" "${PPTP_PORT}/tcp" "${HYSTERIA2_PORT}/udp" "${SSH_PORT}/tcp" "500/udp" "4500/udp" "${L2TP_PORT}/udp"; do
  proto=${rule##*/}; port=${rule%%/*}
  if ! iptables -C INPUT -p "$proto" --dport "$port" -j ACCEPT 2>/dev/null; then iptables -A INPUT -p "$proto" --dport "$port" -j ACCEPT || true; fi
done
iptables-save > /etc/iptables/rules.v4 2>/dev/null || true
# SSH core
if [[ -x "$APP_DIR/scripts/repair_ssh.sh" ]]; then
  SSH_PORT="$SSH_PORT" IRONPANEL_SSH_PORT="$SSH_PORT" bash "$APP_DIR/scripts/repair_ssh.sh" --install || CORE_ERRORS+=(ssh-repair)
fi

# OpenVPN core + complete PKI validation/repair.
# Every required artifact is validated individually; a remaining ca.crt no
# longer prevents server.crt, server.key or dh.pem from being restored.
if ! APP_DIR="$APP_DIR" ETC_DIR="$ETC_DIR" bash "$PREREQ_SCRIPT" --ensure-openvpn; then
  CORE_ERRORS+=(openvpn-pki)
fi
OPENVPN_SERVER_PROTO="udp"
if [[ "$OPENVPN_PROTO" == "tcp" ]]; then OPENVPN_SERVER_PROTO="tcp-server"; fi
OPENVPN_CRL_LINE=""
if [[ -s /etc/openvpn/server/crl.pem ]] && openssl crl -in /etc/openvpn/server/crl.pem -noout >/dev/null 2>&1; then OPENVPN_CRL_LINE="crl-verify /etc/openvpn/server/crl.pem"; fi
cat > /etc/openvpn/server/server.conf <<OVPN
port $OPENVPN_PORT
proto $OPENVPN_SERVER_PROTO
dev tun
topology subnet
server 10.8.0.0 255.255.255.0
push "redirect-gateway def1 bypass-dhcp"
push "dhcp-option DNS 1.1.1.1"
push "dhcp-option DNS 8.8.8.8"
keepalive 10 120
persist-key
persist-tun
# IronPanel OpenVPN runs without privilege drop because client-connect/client-disconnect
# scripts must read/write the IronPanel SQLite database for quota enforcement.
ca /etc/openvpn/server/ca.crt
cert /etc/openvpn/server/server.crt
key /etc/openvpn/server/server.key
dh /etc/openvpn/server/dh.pem
tls-crypt /etc/openvpn/server/tls-crypt.key
auth SHA256
cipher AES-256-GCM
data-ciphers AES-256-GCM:AES-128-GCM:CHACHA20-POLY1305
verify-client-cert require
$OPENVPN_CRL_LINE
status /var/log/openvpn/status.log 10
status-version 2
script-security 2
client-connect /opt/ironpanel/scripts/openvpn_client_connect.sh
client-disconnect /opt/ironpanel/scripts/openvpn_client_disconnect.sh
verb 3
OVPN
for required in /etc/openvpn/server/ca.crt /etc/openvpn/server/server.crt /etc/openvpn/server/server.key /etc/openvpn/server/dh.pem /etc/openvpn/server/tls-crypt.key; do
  [[ -s "$required" ]] || CORE_ERRORS+=("openvpn-file-missing:$required")
done
# Ocserv / Cisco AnyConnect compatible core
mkdir -p /etc/ocserv/certs
if [[ -x "$APP_DIR/scripts/repair_ocserv.sh" ]]; then
  if ! OCSERV_PORT=${OCSERV_TCP:-8445} OCSERV_TCP=${OCSERV_TCP:-8445} OCSERV_UDP=${OCSERV_UDP:-8445} OCSERV_TRANSPORT=${OCSERV_TRANSPORT:-tcp_udp} IRONPANEL_PUBLIC_HOST="$PUBLIC_HOST" ETC_DIR="$ETC_DIR" bash "$APP_DIR/scripts/repair_ocserv.sh"; then
    CORE_ERRORS+=(ocserv-repair)
  fi
else
  CORE_ERRORS+=(ocserv-repair-script-missing)
fi
# L2TP/IPsec core
if [[ ! -f "$ETC_DIR/ipsec.psk" ]]; then openssl rand -base64 24 > "$ETC_DIR/ipsec.psk"; chmod 600 "$ETC_DIR/ipsec.psk"; fi
cat > /etc/ipsec.conf <<'IPSEC'
config setup
  uniqueids=no
  charondebug="ike 1, knl 1, cfg 0"
conn L2TP-PSK
  keyexchange=ikev1
  authby=secret
  type=transport
  left=%any
  leftprotoport=17/1701
  right=%any
  rightprotoport=17/%any
  auto=add
  ike=aes256-sha1-modp1024,3des-sha1-modp1024!
  esp=aes256-sha1,3des-sha1!
  rekey=no
  forceencaps=yes
  dpddelay=30
  dpdtimeout=120
  dpdaction=clear
IPSEC
cat > /etc/ipsec.secrets <<IPSECSEC
%any %any : PSK "$(cat $ETC_DIR/ipsec.psk)"
IPSECSEC
chmod 600 /etc/ipsec.secrets
cat > /etc/xl2tpd/xl2tpd.conf <<XL2TP
